export function calculateQuizResult(scores: number[]): {
  percentage: number;
  tier: QuizResultTier;
} {
  const totalScore = scores.reduce((sum, current) => sum + current, 0);
  // Formula specified by user: % = 25 + (คะแนนรวม ÷ 45) × 75
  // Kept internal, hidden from user display
  const rawPercentage = 25 + (totalScore / 45) * 75;
  const percentage = Math.min(100, Math.max(25, Math.round(rawPercentage)));

  const tier =
    resultTiers.find(
      (t) => percentage >= t.minPercent && percentage <= t.maxPercent,
    ) || resultTiers[resultTiers.length - 1];

  return { percentage, tier };
}
